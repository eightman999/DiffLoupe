#!/usr/bin/env python3
"""Generate Rust unicode tables: canonical decomposition, composition,
combining classes, full lowercase mappings, and grapheme-extend ranges."""
import unicodedata, sys

MAX = 0x110000
decomp = {}          # cp -> list of cps (canonical only)
ccc = {}             # cp -> int
lower = {}           # cp -> str (full lowercase, context-free entries only)
extend = set()       # cp that continues a grapheme cluster

for cp in range(MAX):
    ch = chr(cp)
    d = unicodedata.decomposition(ch)
    if d and not d.startswith('<'):
        decomp[cp] = [int(x, 16) for x in d.split()]
    c = unicodedata.combining(ch)
    if c:
        ccc[cp] = c
    l = ch.lower()
    if l != ch:
        lower[cp] = l
    cat = unicodedata.category(ch)
    if cat in ('Mn', 'Me', 'Mc'):
        extend.add(cp)

# Composition pairs verified empirically via Python's own NFC (excludes
# composition exclusions automatically).
comp = {}
for cp, ds in decomp.items():
    if len(ds) == 2:
        a, b = ds
        if unicodedata.normalize('NFC', chr(a) + chr(b)) == chr(cp):
            comp[(a, b)] = cp

# Additional extend ranges: variation selectors, emoji modifiers, tag chars
for cp in list(range(0xFE00, 0xFE10)) + list(range(0xE0100, 0xE01F0)) \
        + list(range(0x1F3FB, 0x1F400)) + list(range(0xE0020, 0xE0080)):
    extend.add(cp)

def ranges(cps):
    out = []
    cps = sorted(cps)
    if not cps:
        return out
    s = p = cps[0]
    for c in cps[1:]:
        if c == p + 1:
            p = c
        else:
            out.append((s, p)); s = p = c
    out.append((s, p))
    return out

lines = []
lines.append('// Generated by core/tools/gen_unicode_tables.py (Unicode %s)' % unicodedata.unidata_version)
lines.append('// Do not edit by hand.')
lines.append('')
# decomposition table (canonical)
items = sorted(decomp.items())
lines.append('pub static DECOMP: &[(u32, &\'static [u32])] = &[')
for cp, ds in items:
    lines.append('    (0x%X, &[%s]),' % (cp, ', '.join('0x%X' % d for d in ds)))
lines.append('];')
lines.append('')
lines.append('pub static COMPOSE: &[(u32, u32, u32)] = &[')
for (a, b), c in sorted(comp.items()):
    lines.append('    (0x%X, 0x%X, 0x%X),' % (a, b, c))
lines.append('];')
lines.append('')
lines.append('pub static CCC: &[(u32, u8)] = &[')
for cp, v in sorted(ccc.items()):
    lines.append('    (0x%X, %d),' % (cp, v))
lines.append('];')
lines.append('')
lines.append('/// (cp, [lower cps]) full lowercase mapping, excluding context rules.')
lines.append('pub static LOWER: &[(u32, &\'static [u32])] = &[')
for cp, s in sorted(lower.items()):
    if cp == 0x3A3:  # Sigma handled with context rule at runtime
        continue
    lines.append('    (0x%X, &[%s]),' % (cp, ', '.join('0x%X' % ord(ch) for ch in s)))
lines.append('];')
lines.append('')
lines.append('/// Grapheme-cluster "extend" codepoint ranges (approximation).')
lines.append('pub static EXTEND_RANGES: &[(u32, u32)] = &[')
for a, b in ranges(extend):
    lines.append('    (0x%X, 0x%X),' % (a, b))
lines.append('];')

open('core/crates/diffloupe-core/src/unicode_tables.rs', 'w').write('\n'.join(lines) + '\n')
print('written:', len(decomp), 'decomp,', len(comp), 'comp,', len(ccc), 'ccc,', len(lower), 'lower')
